import React from "react";
// 160px copy of the 1024px master (drawn at 32–64 CSS px); see scratch/generate-responsive-variants.mjs.
import ridozLogoPng from "@/assets/ridoz-logo-160.png";
import wordmark240 from "@/assets/brand/ridoz-wordmark-240.webp";
import wordmark480 from "@/assets/brand/ridoz-wordmark-480.webp";
import { cn } from "@/lib/utils";

export interface BrandLogoProps {
  /**
   * Logo visual variant:
   * - "full": Official burgundy circular symbol with "Style" script inside bottom opening
   * - "symbol": Isolated burgundy open circular ring symbol
   * - "lockup": Brand mark paired with "RIDOZ." display typography
   */
  variant?: "full" | "symbol" | "lockup";
  /** Preset size variants */
  size?: "sm" | "md" | "lg" | "xl" | "custom";
  /** Optional link href (e.g. "/" or "#drop"). Set to null or "" to render as a div */
  href?: string | null;
  /** Whether to show the "RIDOZ." display wordmark alongside the mark */
  showWordmark?: boolean;
  /** Layout direction for lockup */
  layout?: "horizontal" | "vertical";
  /** Optional custom class name applied to container */
  className?: string;
  /** Optional custom class name applied to logo image */
  imageClassName?: string;
  /** Eager vs lazy loading */
  priority?: boolean;
}

const sizeConfig = {
  sm: {
    height: 32,
    width: 32,
    imgClass: "h-8 w-auto",
    textClass: "h-5",
  },
  md: {
    height: 40,
    width: 40,
    imgClass: "h-10 w-auto",
    textClass: "h-6",
  },
  lg: {
    height: 48,
    width: 48,
    imgClass: "h-12 w-auto",
    textClass: "h-7",
  },
  xl: {
    height: 64,
    width: 64,
    imgClass: "h-16 w-auto",
    textClass: "h-9",
  },
  custom: {
    height: 40,
    width: 40,
    imgClass: "",
    textClass: "h-6",
  },
};

export const BrandLogo: React.FC<BrandLogoProps> = ({
  variant = "full",
  size = "md",
  href = "#drop",
  showWordmark = false,
  layout = "horizontal",
  className,
  imageClassName,
  priority = true,
}) => {
  const currentSize = sizeConfig[size] || sizeConfig.md;
  const isLockup = variant === "lockup" || showWordmark;

  const logoMark = (
    <div
      className={cn(
        "relative flex items-center justify-center shrink-0",
        currentSize.imgClass,
        imageClassName
      )}
      style={{
        aspectRatio: "1 / 1",
      }}
    >
      {variant === "symbol" ? (
        // Scalable SVG burgundy open ring symbol
        <svg
          viewBox="0 0 100 100"
          fill="none"
          xmlns="http://www.w3.org/2000/svg"
          className="h-full w-full object-contain"
          aria-hidden="true"
        >
          <path
            d="M 26.82 83.02 A 42 42 0 1 1 73.18 83.02 L 65.34 71.18 A 27.8 27.8 0 1 0 34.66 71.18 Z"
            fill="var(--primary, #a51538)"
          />
        </svg>
      ) : (
        // Full official brand logo (Burgundy ring + "Style" script)
        <img
          src={ridozLogoPng}
          alt="RIDOZ Style"
          width={currentSize.width}
          height={currentSize.height}
          loading={priority ? "eager" : "lazy"}
          decoding="async"
          className="h-full w-auto object-contain select-none"
        />
      )}
    </div>
  );

  // Official RIDOZ wordmark image, drawn at roughly the cap height of the old text.
  const wordmark = <BrandWordmark decorative={!!href} priority={priority} className={currentSize.textClass} />;

  const content = isLockup ? (
    <div
      className={cn(
        "inline-flex items-center gap-2.5",
        layout === "vertical" && "flex-col items-center gap-3 text-center",
        className
      )}
    >
      {logoMark}
      {wordmark}
    </div>
  ) : (
    <div className={cn("inline-flex items-center", className)}>
      {logoMark}
    </div>
  );

  if (href) {
    return (
      <a
        href={href}
        aria-label="RIDOZ Style, back to top"
        className="group inline-flex items-center transition-opacity hover:opacity-95"
      >
        {content}
      </a>
    );
  }

  return content;
};

export interface BrandWordmarkProps {
  /** Height utility, e.g. "h-6". Width follows the 1200:347 aspect ratio. */
  className?: string;
  /** Eager vs lazy loading */
  priority?: boolean;
  /** Set when a parent already labels the logo (e.g. a link with aria-label). */
  decorative?: boolean;
  /** Drawn width for srcset selection (CSS "sizes"); match it to className. */
  sizes?: string;
}

/**
 * Official "RIDOZ" wordmark (with "Style" inside the O) in brand burgundy.
 * Generated by scratch/generate-brand-wordmark.mjs; srcset picks the copy for the drawn size + DPR.
 */
export const BrandWordmark: React.FC<BrandWordmarkProps> = ({
  className,
  priority = false,
  decorative = false,
  sizes = "120px",
}) => (
  <img
    src={wordmark240}
    srcSet={`${wordmark240} 240w, ${wordmark480} 480w`}
    sizes={sizes}
    width={480}
    height={139}
    alt={decorative ? "" : "RIDOZ Style"}
    draggable={false}
    loading={priority ? "eager" : "lazy"}
    fetchPriority={priority ? "high" : undefined}
    decoding="async"
    className={cn("block h-6 w-auto select-none", className)}
  />
);

export default BrandLogo;

